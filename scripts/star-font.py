#!/usr/bin/env python3
"""Generates apps/api/src/print/star-font.ts (W-02): the bitmap font Star raster tickets are drawn with.

Printable ASCII (0x20-0x7E, the same characters our ESC/POS tickets print) from DejaVu Sans Mono
and DejaVu Sans Mono Bold, each in a cell 16 dots wide and 32 tall, so a 32-column ticket is 512
dots of the TSP100III's 576. The fonts' licence (Bitstream Vera, DejaVu changes in the public
domain) allows this and asks for its notice in every copy: it goes into the file's header.
Run once; the output is committed. Needs Pillow and the TTFs with LICENSE_DEJAVU (matplotlib ships
them in mpl-data/fonts/ttf):
  python3 scripts/star-font.py <that folder>
"""
import base64
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H, SIZE, BASELINE = 16, 32, 26, 25
FIRST, LAST = 0x20, 0x7E


def glyphs(ttf: Path) -> bytes:
    font = ImageFont.truetype(str(ttf), SIZE)
    ascent, _ = font.getmetrics()
    out = bytearray()
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((0, BASELINE - ascent), chr(code), font=font, fill=255)
        for y in range(H):
            row = 0
            for x in range(W):
                if img.getpixel((x, y)) >= 128:
                    row |= 1 << (W - 1 - x)
            out += row.to_bytes(2, "big")
    return bytes(out)


def main() -> None:
    src = Path(sys.argv[1])
    licence = (src / "LICENSE_DEJAVU").read_text().rstrip().splitlines()
    regular = base64.b64encode(glyphs(src / "DejaVuSansMono.ttf")).decode()
    bold = base64.b64encode(glyphs(src / "DejaVuSansMono-Bold.ttf")).decode()
    dest = Path(__file__).resolve().parent.parent / "apps/api/src/print/star-font.ts"
    header = "\n".join(f"// {line}".rstrip() for line in licence)
    dest.write_text(
        "// Generated by scripts/star-font.py (W-02); don't edit by hand. A bitmap of printable ASCII\n"
        "// drawn from DejaVu Sans Mono and DejaVu Sans Mono Bold, under the fonts' licence:\n"
        "//\n"
        f"{header}\n\n"
        f"export const GLYPH_WIDTH = {W};\n"
        f"export const GLYPH_HEIGHT = {H};\n"
        f"export const FIRST_CHAR = 0x{FIRST:02x};\n"
        f"export const LAST_CHAR = 0x{LAST:02x};\n"
        "/** Per character, GLYPH_HEIGHT rows of two bytes, the leftmost dot in the high bit (base64). */\n"
        f'export const REGULAR = "{regular}";\n'
        f'export const BOLD = "{bold}";\n'
    )
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
